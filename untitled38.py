def create_alexnet():

    model = models.Sequential([

        layers.Input(shape=(32, 32, 3)),

        layers.Conv2D(
            96,
            (3, 3),
            padding="same",
            activation="relu"
        ),

        layers.MaxPooling2D(
            pool_size=(2, 2)
        ),

        layers.Conv2D(
            256,
            (3, 3),
            padding="same",
            activation="relu"
        ),

        layers.MaxPooling2D(
            pool_size=(2, 2)
        ),

        layers.Conv2D(
            384,
            (3, 3),
            padding="same",
            activation="relu"
        ),

        layers.Conv2D(
            384,
            (3, 3),
            padding="same",
            activation="relu"
        ),

        layers.Conv2D(
            256,
            (3, 3),
            padding="same",
            activation="relu"
        ),

        layers.MaxPooling2D(
            pool_size=(2, 2)
        ),

        layers.Flatten(),

        layers.Dense(
            4096,
            activation="relu"
        ),

        layers.Dropout(0.5),

        layers.Dense(
            4096,
            activation="relu"
        ),

        layers.Dropout(0.5),

        layers.Dense(
            10,
            activation="softmax"
        )
    ])

    model.compile(
        optimizer="adam",
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"]
    )

    return model

