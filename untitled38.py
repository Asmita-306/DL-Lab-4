# GOOGLENET / INCEPTION
# ============================================================

def inception_block(
    x,
    filters
):

    f1, f3, f5, fp = filters

    # 1x1 branch
    branch1 = layers.Conv2D(
        f1,
        (1, 1),
        padding="same",
        activation="relu"
    )(x)

    # 3x3 branch
    branch3 = layers.Conv2D(
        f3,
        (1, 1),
        padding="same",
        activation="relu"
    )(x)

    branch3 = layers.Conv2D(
        f3,
        (3, 3),
        padding="same",
        activation="relu"
    )(branch3)

    # 5x5 branch
    branch5 = layers.Conv2D(
        f5,
        (1, 1),
        padding="same",
        activation="relu"
    )(x)

    branch5 = layers.Conv2D(
        f5,
        (5, 5),
        padding="same",
        activation="relu"
    )(branch5)

    # Pooling branch
    branch_pool = layers.MaxPooling2D(
        (3, 3),
        strides=(1, 1),
        padding="same"
    )(x)

    branch_pool = layers.Conv2D(
        fp,
        (1, 1),
        padding="same",
        activation="relu"
    )(branch_pool)

    # Concatenate
    output = layers.Concatenate()([
        branch1,
        branch3,
        branch5,
        branch_pool
    ])

    return output


def create_googlenet():

    inputs = layers.Input(
        shape=(32, 32, 3)
    )

    x = layers.Conv2D(
        64,
        (3, 3),
        padding="same",
        activation="relu"
    )(inputs)

    x = layers.MaxPooling2D(
        (2, 2)
    )(x)

    x = inception_block(
        x,
        (32, 64, 16, 16)
    )

    x = inception_block(
        x,
        (64, 96, 32, 32)
    )

    x = layers.MaxPooling2D(
        (2, 2)
    )(x)

    x = inception_block(
        x,
        (96, 128, 32, 64)
    )

    x = inception_block(
        x,
        (128, 160, 48, 64)
    )

    x = layers.GlobalAveragePooling2D()(x)

    x = layers.Dropout(0.4)(x)

    outputs = layers.Dense(
        10,
        activation="softmax"
    )(x)

    model = models.Model(
        inputs,
        outputs
    )

    model.compile(
        optimizer="adam",
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"]
    )

    return model

