import pandas as pd
import gc

def create_hyperparameter_model(
    learning_rate=0.001,
    optimizer_name="Adam",
    dense_units=128,
    freeze_type="all"
):

    base = MobileNetV2(
        weights="imagenet",
        include_top=False,
        input_shape=(96, 96, 3)
    )

    # --------------------------------------------------------
    # Freeze configuration
    # --------------------------------------------------------

    if freeze_type == "all":

        base.trainable = False

    else:

        base.trainable = True

        # Freeze everything first
        for layer in base.layers:
            layer.trainable = False

        # Unfreeze last MobileNetV2 block
        unfreeze = False

        for layer in base.layers:

            if layer.name.startswith("block_16"):
                unfreeze = True

            if unfreeze:
                layer.trainable = True

        # Keep BatchNormalization frozen
        for layer in base.layers:
            if isinstance(
                layer,
                tf.keras.layers.BatchNormalization
            ):
                layer.trainable = False

    # --------------------------------------------------------
    # Build model
    # --------------------------------------------------------

    temp_model = models.Sequential([

        layers.Input(shape=(32, 32, 3)),

        layers.Resizing(96, 96),

        layers.Rescaling(
            2.0,
            offset=-1.0
        ),

        base,

        layers.GlobalAveragePooling2D(),

        layers.Dense(
            dense_units,
            activation="relu"
        ),

        layers.Dense(
            10,
            activation="softmax"
        )
    ])

    # --------------------------------------------------------
    # Optimizer
    # --------------------------------------------------------

    if optimizer_name == "Adam":

        optimizer = tf.keras.optimizers.Adam(
            learning_rate=learning_rate
        )

    else:

        optimizer = tf.keras.optimizers.SGD(
            learning_rate=learning_rate
        )

    # --------------------------------------------------------
    # Compile
    # --------------------------------------------------------

    temp_model.compile(
        optimizer=optimizer,
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"]
    )

    return temp_model


